# VinFast model names are public; used here only as template strings. The
# randomized per-record fields (version, color, price, etc.) are the only
# variation, and they all carry the SYNTH marker downstream.
VF_MODELS = [
    ("VF 3", ["Plus", "Eco"]),
    ("VF 5", ["Plus", "Eco"]),
    ("VF 6", ["Plus", "Eco"]),
    ("VF 7", ["Plus", "Eco"]),
    ("VF 8", ["Plus", "Eco", "Lux"]),
    ("VF 9", ["Plus", "Eco", "Lux"]),
]

# Real-looking but obviously fake bank names (all carry SYNTH- marker).
FAKE_BANKS = [
    "SYNTH Ngân hàng TMCP Á Đông Dương",
    "SYNTH Ngân hàng TMCP Phương Đông Việt",
    "SYNTH Ngân hàng TMCP Đại Việt",
    "SYNTH Ngân hàng TMCP Tổng Hợp Sài Gòn",
    "SYNTH Ngân hàng TMCP Bắc Trung Nam",
]

VEHICLE_COLORS = [
    "Trắng", "Đen", "Bạc", "Xám", "Đỏ", "Xanh dương", "Xanh lá",
]


@dataclass
class SynthContract:
    case_id: str
    source_pdf: str
    contract_no: str
    sign_date: str
    seller_name: str
    seller_address: str
    seller_tax_id: str
    seller_rep: str
    seller_rep_title: str
    seller_bank: str
    seller_account: str
    seller_account_holder: str
    buyer_name: str
    buyer_address: str
    buyer_phone: str
    buyer_email: str
    buyer_id: str
    model: str
    version: str
    color: str
    vin: str
    includes_battery: bool
    unit_price_vnd: int
    total_price_words_vi: str
    payment_stage_1_vnd: int
    payment_method: str  # "trả thẳng" | "trả góp"
    own_capital_vnd: int | None
    credit_notice_vnd: int | None
    delivery_date: str
    delivery_place: str
    special_offer_a: str = ""
    special_offer_b: str = ""
    special_offer_c: str = ""
    special_offer_d: str = ""
    page2_notes: list[str] = field(default_factory=list)


def _rand_digits(n: int, rng: random.Random) -> str:
    return "".join(rng.choice(string.digits) for _ in range(n))


def _rand_upper(n: int, rng: random.Random) -> str:
    return "".join(rng.choice(string.ascii_uppercase) for _ in range(n))


def _vi_amount_words(amount_vnd: int) -> str:
    """Money-in-words for GT field. OCR text layer uses digit form, so this
    string is only used to populate `ground_truth_fields.total_price_words_vi`.
    """
    return f"{amount_vnd:,} đồng (SYNTH — số tiền bằng chữ tự sinh)"


def _generate_one(idx: int, seed: int) -> SynthContract:
    rng = random.Random(seed)
    faker = Faker("vi_VN")
    Faker.seed(seed)

    model, versions = rng.choice(VF_MODELS)
    version = rng.choice(versions)
    color = rng.choice(VEHICLE_COLORS)

    # VIN follows a realistic 17-char pattern but always prefixed SYNTH.
    vin = "SYNTH" + _rand_upper(2, rng) + _rand_digits(10, rng)
    includes_battery = rng.random() < 0.55  # ~55% of deals include the battery

    # Realistic-ish VND price band per model.
    base_price = {
        "VF 3": (340_000_000, 420_000_000),
        "VF 5": (520_000_000, 620_000_000),
        "VF 6": (680_000_000, 780_000_000),
        "VF 7": (880_000_000, 1_000_000_000),
        "VF 8": (1_050_000_000, 1_300_000_000),
        "VF 9": (1_500_000_000, 1_900_000_000),
    }[model]
    # Round to nearest 10M VND for clean OCR reads.
    unit_price = rng.randrange(base_price[0], base_price[1], 10_000_000)
    stage1 = round(unit_price * rng.uniform(0.10, 0.30), -6)
    stage1 = max(stage1, 50_000_000)

    payment_method = "trả góp" if rng.random() < 0.45 else "trả thẳng"
    own_capital = None
    credit_notice = None
    if payment_method == "trả góp":
        own_capital = round(unit_price * rng.uniform(0.20, 0.40), -6)
        credit_notice = unit_price - own_capital

    sign_date = faker.date_between(start_date="-90d", end_date="today").isoformat()
    delivery_date = (
        faker.date_between(start_date="today", end_date="+60d").isoformat()
    )

    return SynthContract(
        case_id=f"synth-ctr-{idx:03d}",
        source_pdf=f"contract_synth-ctr-{idx:03d}.pdf",
        contract_no=f"SYNTH-CTR-{idx:03d}/{seed % 9999:04d}",
        sign_date=sign_date,
        seller_name="Công ty TNHH Kinh doanh Ô tô Điện SYNTH Việt Nam",
        seller_address=faker.address().replace("\n", ", "),
        seller_tax_id=f"SYNTH{_rand_digits(10, rng)}",
        seller_rep=faker.name(),
        seller_rep_title=rng.choice(
            ["Giám đốc", "Phó Giám đốc", "Trưởng phòng Kinh doanh"]
        ),
        seller_bank=rng.choice(FAKE_BANKS),
        seller_account=_rand_digits(12, rng),
        seller_account_holder="Công ty TNHH Kinh doanh Ô tô Điện SYNTH Việt Nam",
        buyer_name=f"SYNTH-{faker.name()}",
        buyer_address=faker.address().replace("\n", ", "),
        buyer_phone=f"+84-SYNTH-{_rand_digits(9, rng)}",
        buyer_email=f"buyer.{idx:03d}@example.test",
        buyer_id=f"SYNTH{_rand_digits(9, rng)}",
        model=model,
        version=version,
        color=color,
        vin=vin,
        includes_battery=includes_battery,
        unit_price_vnd=unit_price,
        total_price_words_vi=_vi_amount_words(unit_price),
        payment_stage_1_vnd=int(stage1),
        payment_method=payment_method,
        own_capital_vnd=int(own_capital) if own_capital else None,
        credit_notice_vnd=int(credit_notice) if credit_notice else None,
        delivery_date=delivery_date,
        delivery_place=faker.city(),
        special_offer_a="Ưu đãi giảm 2% theo CTKM SYNTH-AUTUMN-2026",
        special_offer_b="Tặng 5.000.000 VNĐ phụ kiện chính hãng",
        special_offer_c="CBNV cấp bậc Senior — giảm thêm 1,5%",
        special_offer_d="Vinclub hạng Gold — tích điểm 1,2x",
        page2_notes=[
            "Khách Hàng cần duy trì eSIM để sử dụng các tính năng thông minh.",
            "Bên Bán sẽ xử lý dữ liệu cá nhân theo Chính sách Bảo vệ Dữ liệu Cá nhân SYNTH.",
        ],
    )


