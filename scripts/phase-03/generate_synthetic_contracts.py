"""
Generate a synthetic OCR eval corpus for Phase 03.

Produces ~15 Vietnamese "VinFast-style" purchase contracts as **text-selectable PDFs**
(text layer intact, so OCR providers must extract from a real PDF, not just an image),
paired with a ground-truth JSONL that downstream Track-1 extraction configs can be
scored against.

All names, addresses, IDs, numbers are procedurally generated by `Faker` and prefixed
with a clear "SYNTH-" marker so a human reader cannot mistake them for real data.

Output layout
-------------
    data/Scan/synth_phase03/contract_<slug>.pdf          (15 PDFs)
    data/processed/phase03_synth_contracts.jsonl          (15 GT records, paired by case_id)
    data/Scan/synth_phase03/manifest.json                 (run-level metadata)

The GT JSONL mirrors the layout of the (future) EvalLog schema: case_id, source_pdf,
ground_truth_fields (dict).  Track-1 configs (Phase 04) will score against this.

Usage
-----
    conda activate vsf
    python scripts/phase-03/generate_synthetic_contracts.py --n 15

Notes
-----
* Phase 03 is currently `not started` in doc/phases/INDEX.md — this script is the
  seed asset, not an experiment.  The first OCR bake-off run will live in a
  separate `run_ocr_*.py`.
* PDFs use DejaVuSans (registered from this script's `fonts/` folder) so
  Vietnamese diacritics render correctly. The fonts are bundled with
  matplotlib (Bitstream-Vera + font-exception license) and copied into the
  repo so the generator is self-contained and offline-deterministic.
* Data is 100% synthetic. No real VinFast customer, dealer, or bank data is
  reused. Every identifier carries a SYNTH- prefix or a @example.test domain.
"""
