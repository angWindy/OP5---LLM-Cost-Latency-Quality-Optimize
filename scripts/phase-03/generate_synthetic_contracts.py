def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate synthetic VinFast-style OCR contracts."
    )
    parser.add_argument(
        "--n",
        type=int,
        default=15,
        help="Number of contracts to generate (must be in [10, 20]).",
    )
    parser.add_argument(
        "--seed-base",
        type=int,
        default=20260925,
        help="Base seed (case i uses seed_base + i).",
    )
    args = parser.parse_args()

    if not 10 <= args.n <= 20:
        raise SystemExit(f"--n must be in [10, 20] (got {args.n}).")

    contracts = [_generate_one(i + 1, args.seed_base + i) for i in range(args.n)]

    # Render PDFs
    for c in contracts:
        out_pdf = SCAN_OUT / c.source_pdf
        render_contract_pdf(c, out_pdf)

    # Write GT JSONL (one record per case, paired by case_id)
    with GT_OUT.open("w", encoding="utf-8") as f:
        for c in contracts:
            record = {
                "case_id": c.case_id,
                "source_pdf": str(Path("data/Scan") / "synth_phase03" / c.source_pdf),
                "schema_version": "phase03.synth.v1",
                "language": "vi",
                "ground_truth_fields": asdict(c),
            }
            f.write(json.dumps(record, ensure_ascii=False) + "\n")

    # Manifest
    manifest = {
        "phase": "03-ocr-bake-off",
        "asset_kind": "synthetic-pdf-corpus",
        "n": args.n,
        "seed_base": args.seed_base,
        "schema_version": "phase03.synth.v1",
        "pdf_dir": str(SCAN_OUT.relative_to(REPO_ROOT)),
        "gt_jsonl": str(GT_OUT.relative_to(REPO_ROOT)),
        "synthetic_marker": "SYNTH- prefix on every identifier; @example.test emails.",
        "case_ids": [c.case_id for c in contracts],
    }
    MANIFEST_OUT.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    print(f"Wrote {args.n} PDFs to {SCAN_OUT}")
    print(f"Wrote GT JSONL  to {GT_OUT}")
    print(f"Wrote manifest  to {MANIFEST_OUT}")


if __name__ == "__main__":
    main()
